# make_font.py <font.ttf> <out.h>: renders printable ASCII (32..126) in a monospace TrueType font into
# a 9x18 alpha atlas with ffmpeg's drawtext filter, as a C header for cqconsole.c.
import os, subprocess, sys, tempfile
ttf, out = sys.argv[1], sys.argv[2]
W, H, SIZE = 9, 18, 15
chars = range(32, 127)
with tempfile.TemporaryDirectory() as d:
    parts = []
    for i, c in enumerate(chars):
        p = os.path.join(d, f'{c}.txt')
        with open(p, 'w') as f:
            f.write(chr(c))
        parts.append(f"drawtext=fontfile='{ttf}':textfile='{p}':expansion=none:fontsize={SIZE}:"
                     f"fontcolor=white:x={i * W}:y=14-ascent")
    script = os.path.join(d, 'font.filter')
    with open(script, 'w') as f:
        f.write(','.join(parts))
    raw = subprocess.run(['ffmpeg', '-loglevel', 'error', '-f', 'lavfi', '-i', f'color=black:s={W * len(chars)}x{H}',
                          '-frames:v', '1', '-filter_script:v', script, '-pix_fmt', 'gray', '-f', 'rawvideo', '-'],
                         check=True, capture_output=True).stdout
assert len(raw) == W * H * len(chars), len(raw)
with open(out, 'w') as f:
    f.write(f'// Generated by make_font.py from {os.path.basename(ttf)}: {len(chars)} glyphs, {W}x{H}, alpha.\n')
    f.write(f'#define FONT_W {W}\n#define FONT_H {H}\n#define FONT_FIRST 32\n#define FONT_COUNT {len(chars)}\n')
    f.write('static const unsigned char kFont[] = {\n')
    for i in range(0, len(raw), 24):
        f.write('  ' + ','.join(str(b) for b in raw[i:i + 24]) + ',\n')
    f.write('};\n')
