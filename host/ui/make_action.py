# make_action.py <empty.swf | compiled.swf> <out.h> [--empty | array name]: with --empty, writes a one-frame SWF
# with an empty DoAction (for FFDec to compile a script into); otherwise copies the compiled
# DoAction tag out of the SWF into a C header.
import struct, sys

def tag(code, body):
    return struct.pack('<HI', code << 6 | 0x3f, len(body)) + body

if '--empty' in sys.argv:
    body = b'\x00' + struct.pack('<HH', 0x1800, 1) + tag(12, b'\x00') + tag(1, b'') + b'\x00\x00'
    open(sys.argv[1], 'wb').write(b'FWS\x08' + struct.pack('<I', 8 + len(body)) + body)
    sys.exit()

d = open(sys.argv[1], 'rb').read()
name = sys.argv[3] if len(sys.argv) > 3 else 'kAdvancedAction'
p = 8 + (5 + 4 * (d[8] >> 3) + 7) // 8 + 4
while p < len(d):
    h = struct.unpack_from('<H', d, p)[0]
    code, ln, hl = h >> 6, h & 63, 2
    if ln == 63:
        ln, hl = struct.unpack_from('<I', d, p + 2)[0], 6
    if code == 12:
        t = d[p:p + hl + ln]
        break
    p += hl + ln
else:
    sys.exit('no DoAction')
rows = [', '.join('0x%02x' % b for b in t[i:i + 16]) for i in range(0, len(t), 16)]
open(sys.argv[2], 'w').write(
    '// SPDX-License-Identifier: CC0-1.0\n'
    '// Generated by host/ui/build.sh: a SWF DoAction tag. Do not edit.\n'
    '#pragma once\n'
    'static const unsigned char %s[%d] = {\n    %s,\n};\n' % (name, len(t), ',\n    '.join(rows)))
print('%s: %d bytes' % (sys.argv[2], len(t)))
