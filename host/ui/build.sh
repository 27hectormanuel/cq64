# build.sh: compiles the menu fixes added to the game's own movies into ../src/menu_fixes_action.h
# (needs Java and JPEXS FFDec: FFDEC=<path to ffdec.jar>). Run it after changing a script.
#   notebook_fix.as   -> kNotebookFix   (Notebook_DLC.gfx, the journal)
#   stampshop_fix.as  -> kStampShopFix  (StampShop_DLC.gfx, the stamp shop)
#   battlehud_fix.as  -> kBattleHudFix  (BattleHUD_DLC.gfx, the battle HUD)
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
FFDEC=${FFDEC:?set FFDEC to ffdec.jar}
OUT=$HERE/../src/menu_fixes_action.h
T=$(mktemp -d)
trap 'rm -rf "$T"' EXIT
python3 "$HERE/make_action.py" "$T/empty.swf" - --empty
compile() {  # <script> <array name>
    rm -rf "$T/src" && mkdir -p "$T/src/scripts/frame_1"
    cp "$HERE/$1" "$T/src/scripts/frame_1/DoAction.as"
    java -jar "$FFDEC" -importScript "$T/empty.swf" "$T/out.swf" "$T/src" >/dev/null
    python3 "$HERE/make_action.py" "$T/out.swf" "$T/$2.h" "$2" >/dev/null
}
compile notebook_fix.as kNotebookFix
compile stampshop_fix.as kStampShopFix
compile battlehud_fix.as kBattleHudFix
{
    echo '// SPDX-License-Identifier: CC0-1.0'
    echo '// Generated by host/ui/build.sh: SWF DoAction tags (host/ui/*_fix.as). Do not edit.'
    echo '#pragma once'
    sed '1,3d' "$T/kNotebookFix.h"
    sed '1,3d' "$T/kStampShopFix.h"
    sed '1,3d' "$T/kBattleHudFix.h"
} > "$OUT"
echo "$OUT: $(grep -c '^static' "$OUT") scripts"
